test('增量判断同陪衬离场：逐段喂和一次喂整段结果一致', () => {
    const others = ['苏念', '司徒言'];
    const texts = ['苏念坐了下来。', '李伯躬身退下。', '苏念走出房间。李伯又回来了。', '你独自走出了教室，李伯没有跟上。', '李伯小跑着跟了上来。', '你转身走向车站', '李伯站在原地。'];
    for (let from = 0; from < texts.length; from++) {
        const tracker = createCastLeftTracker({ name: '李伯', others, pronoun: false });
        let acc = '', last;
        for (let i = from; i < texts.length; i++) {
            acc += texts[i] + (i < texts.length - 1 ? '\n' : '');
            last = tracker.feed(texts[i] + (i < texts.length - 1 ? '\n' : ''), texts[i + 1] || '');
            // 整段一次判断时没有「下一页」信息：只在没有下一页可看时严格对照。
            if (i === texts.length - 1) assert.equal(last, narrationCastLeft({ name: '李伯', others, text: acc, pronoun: false }), `从第 ${from} 段起`);
        }
    }
});

